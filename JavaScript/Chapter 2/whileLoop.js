// While loops are used to execute a block of code repeatedly as long as a specified condition is true. The syntax for a while loop is as follows:

let i = 1;

while(i >= 4){
    console.log(`Hello ${i}`);
    i++;
}

// Do while loops are similar to while loops, but they guarantee that the block of code will be executed at least once, even if the condition is false. The syntax for a do while loop is as follows:

let a = 1;

do {
  console.log(`Merhaba ${a}`);
  a++;
} while (a >= 4);
